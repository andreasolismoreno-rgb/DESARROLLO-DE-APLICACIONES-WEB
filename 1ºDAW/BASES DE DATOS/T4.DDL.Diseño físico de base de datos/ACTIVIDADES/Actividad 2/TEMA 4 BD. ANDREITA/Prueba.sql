-- 1. Crear tabla limpia
CREATE TABLE TIENDAS (
    NIF VARCHAR2(10),
    NOMBRE VARCHAR2(20),
    DIRECCION VARCHAR2(20),
    POBLACION VARCHAR2(20),
    PROVINCIA VARCHAR2(20),
    CODPOSTAL NUMBER(5)
);

-- 2. Añadir PK
ALTER TABLE TIENDAS ADD CONSTRAINT PK_NIF PRIMARY KEY (NIF);

//Provincia en Mayúsculas  Restricción CHECK con UPPER
ALTER TABLE TIENDAS ADD CONSTRAINT CK_PROV_MAYUS CHECK (PROVINCIA = UPPER(PROVINCIA));

//Cambiar longitud NOMBRE a 30 y NOT NULL
ALTER TABLE TIENDAS MODIFY (NOMBRE VARCHAR2(30) NOT NULL);




//Crear tabla Fabricantes
CREATE TABLE FABRICANTES (
    COD_FABRICANTE NUMBER(3) CONSTRAINT PK_FAB PRIMARY KEY,
    NOMBRE VARCHAR2(15) CONSTRAINT CK_FAB_NOM CHECK (NOMBRE = UPPER(NOMBRE)),
    PAIS VARCHAR2(15) CONSTRAINT CK_FAB_PAIS CHECK (PAIS = UPPER(PAIS))
);


//Crear tabla articulos
CREATE TABLE ARTICULOS (
    ARTICULO VARCHAR2(20),
    COD_FABRICANTE NUMBER(3),
    PESO NUMBER(3),
    CATEGORIA VARCHAR2(10),
    PRECIO_VENTA NUMBER(6),
    PRECIO_COSTO NUMBER(6),
    EXISTENCIAS NUMBER(5),
    -- Clave Primaria Compuesta
    CONSTRAINT PK_ARTICULOS PRIMARY KEY (ARTICULO, COD_FABRICANTE, PESO, CATEGORIA),
    -- Clave Ajena
    CONSTRAINT FK_ART_FABRICANTE FOREIGN KEY (COD_FABRICANTE) REFERENCES FABRICANTES(COD_FABRICANTE),
    -- Validación de valores mayores a cero
    CONSTRAINT CK_ART_POSITIVOS CHECK (PRECIO_VENTA > 0 AND PRECIO_COSTO > 0 AND PESO > 0)
);



//Crear tabla VENTAS
CREATE TABLE VENTAS (
    NIF VARCHAR2(10),
    ARTICULO VARCHAR2(20),
    COD_FABRICANTE NUMBER(3),
    PESO NUMBER(3),
    CATEGORIA VARCHAR2(10),
    FECHA_VENTA DATE,
    UNIDADES_VENDIDAS NUMBER(4),
    CONSTRAINT PK_VENTAS PRIMARY KEY (NIF, ARTICULO, COD_FABRICANTE, PESO, CATEGORIA, FECHA_VENTA),
    CONSTRAINT FK_VENTAS_TIENDA FOREIGN KEY (NIF) REFERENCES TIENDAS(NIF),
    CONSTRAINT FK_VENTAS_ARTICULO FOREIGN KEY (ARTICULO, COD_FABRICANTE, PESO, CATEGORIA) 
        REFERENCES ARTICULOS(ARTICULO, COD_FABRICANTE, PESO, CATEGORIA),
    CONSTRAINT CK_VENTAS_UNIDADES CHECK (UNIDADES_VENDIDAS > 0),
    CONSTRAINT CK_VENTAS_CATEGORIA CHECK (CATEGORIA IN ('Primera', 'Segunda', 'Tercera'))
);

//Crear tabla ARTICULOS
CREATE TABLE PEDIDOS (
    NIF VARCHAR2(10),
    ARTICULO VARCHAR2(20),
    COD_FABRICANTE NUMBER(3),
    PESO NUMBER(3),
    CATEGORIA VARCHAR2(10),
    FECHA_PEDIDO DATE,
    UNIDADES_PEDIDAS NUMBER(4),
    EXISTENCIAS NUMBER(5),
    CONSTRAINT PK_PEDIDOS PRIMARY KEY (NIF, ARTICULO, COD_FABRICANTE, PESO, CATEGORIA, FECHA_PEDIDO),
    CONSTRAINT FK_PEDIDOS_TIENDA FOREIGN KEY (NIF) REFERENCES TIENDAS(NIF),
    CONSTRAINT FK_PEDIDOS_ARTICULO FOREIGN KEY (ARTICULO, COD_FABRICANTE, PESO, CATEGORIA) 
        REFERENCES ARTICULOS(ARTICULO, COD_FABRICANTE, PESO, CATEGORIA),
    CONSTRAINT CK_PEDIDOS_UNIDADES CHECK (UNIDADES_PEDIDAS > 0),
    CONSTRAINT CK_PEDIDOS_CATEGORIA CHECK (CATEGORIA IN ('Primera', 'Segunda', 'Tercera'))
);


