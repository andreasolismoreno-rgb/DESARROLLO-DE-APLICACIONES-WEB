-- 1. TABLA DIRECTOR (Maestra)
CREATE TABLE DIRECTOR (
    NOMBRE VARCHAR2(60),
    NACIONALIDAD VARCHAR2(40),
    CONSTRAINT PK_DIRECTOR PRIMARY KEY (NOMBRE)
);
DESC DIRECTOR;

-- 2. TABLA ACTORES (Maestra)
CREATE TABLE ACTORES (
    NOMBRE VARCHAR2(60),
    NACIONALIDAD VARCHAR2(40),
    -- CHECK: Restringe los valores a H o M.
    SEXO CHAR(1) CONSTRAINT CK_SEXO CHECK (SEXO IN ('H', 'M')),
    CONSTRAINT PK_ACTORES PRIMARY KEY (NOMBRE)
);
DESC ACTORES;

-- 3. TABLA PELICULA (Depende de Director)
CREATE TABLE PELICULA (
    ID NUMBER(10),
    TITULO VARCHAR2(100) NOT NULL, -- Obligatorio por enunciado
    PRODUCTORA VARCHAR2(60),
    NACIONALIDAD VARCHAR2(40),
    FECHA DATE,
    DIRECTOR VARCHAR2(60),
    CONSTRAINT PK_PELICULA PRIMARY KEY (ID),
    -- Relación 1:N: Un director dirige muchas películas.
    CONSTRAINT FK_PELI_DIR FOREIGN KEY (DIRECTOR) REFERENCES DIRECTOR(NOMBRE)
);
DESC PELICULA;

-- 4. TABLA EJEMPLAR (Entidad Débil - Depende de Película)
CREATE TABLE EJEMPLAR (
    ID_PELI NUMBER(10),
    NUMERO NUMBER(5),
    ESTADO VARCHAR2(20),
    -- PK Compuesta: Identifica el ejemplar específico de una película.
    CONSTRAINT PK_EJEMPLAR PRIMARY KEY (ID_PELI, NUMERO),
    CONSTRAINT FK_EJEM_PELI FOREIGN KEY (ID_PELI) REFERENCES PELICULA(ID)
);
DESC EJEMPLAR;

-- 5. TABLA SOCIO (Relación Reflexiva)
CREATE TABLE SOCIO (
    DNI VARCHAR2(9),
    NOMBRE VARCHAR2(60) NOT NULL, -- Obligatorio por enunciado
    DIRECCION VARCHAR2(100),
    TELEFONO VARCHAR2(15),
    AVALADOR VARCHAR2(9),
    CONSTRAINT PK_SOCIO PRIMARY KEY (DNI),
    -- RELACIÓN 1:N REFLEXIVA: Un socio puede avalar a muchos otros socios.
    CONSTRAINT FK_SOCIO_AVALADOR FOREIGN KEY (AVALADOR) REFERENCES SOCIO(DNI)
);
DESC SOCIO;

-- 6. TABLA ALQUILA (Relación N:M entre Socio y Ejemplar)
CREATE TABLE ALQUILA (
    DNI VARCHAR2(9),
    ID_PELI NUMBER(10),
    NUMERO NUMBER(5),
    FECHAALQUILER DATE,
    FECHADEVOLUCION DATE,
    CONSTRAINT PK_ALQUILA PRIMARY KEY (DNI, ID_PELI, NUMERO, FECHAALQUILER),
    CONSTRAINT FK_ALQ_SOCIO FOREIGN KEY (DNI) REFERENCES SOCIO(DNI),
    CONSTRAINT FK_ALQ_EJEM FOREIGN KEY (ID_PELI, NUMERO) REFERENCES EJEMPLAR(ID_PELI, NUMERO),
    -- CHECK: FechaDevolucion debe ser posterior a FechaAlquiler.
    CONSTRAINT CK_FECHAS CHECK (FECHADEVOLUCION > FECHAALQUILER)
);
DESC ALQUILA;

-- 7. TABLA ACTUA (Relación N:M entre Actores y Película)
CREATE TABLE ACTUA (
    ACTOR VARCHAR2(60),
    ID_PELI NUMBER(10),
    -- DEFAULT 'N': Si no se indica nada, no es protagonista.
    PROTA CHAR(1) DEFAULT 'N',
    CONSTRAINT PK_ACTUA PRIMARY KEY (ACTOR, ID_PELI),
    CONSTRAINT FK_ACTUA_ACTOR FOREIGN KEY (ACTOR) REFERENCES ACTORES(NOMBRE),
    CONSTRAINT FK_ACTUA_PELI FOREIGN KEY (ID_PELI) REFERENCES PELICULA(ID),
    CONSTRAINT CK_PROTA CHECK (PROTA IN ('S', 'N'))
);
DESC ACTUA;